"""Regenerate ``src/adres/_data.py`` from Turkish Wikipedia.

The source is the table in "Türkiye'nin ilçeleri" (list of districts of
Turkey), pinned to one revision so the output is reproducible. Place names and
postal codes are facts; the table itself is CC BY-SA, credited in the README.

    python scripts/build_data.py            # download the pinned revision
    python scripts/build_data.py page.json  # or use a saved API response
"""

from __future__ import annotations

import json
import re
import sys
import urllib.request
from collections import Counter
from pathlib import Path

REVISION = 37373921  # 2026-06-23
API = (
    "https://tr.wikipedia.org/w/api.php?action=parse&oldid={rev}"
    "&prop=wikitext&format=json&formatversion=2"
)
OUT = Path(__file__).resolve().parent.parent / "src" / "adres" / "_data.py"

# Postal ranges in the source whose prefix does not match the province.
# Obvious one-digit typos are corrected; the rest are dropped rather than guessed.
POSTAL_FIXES = {
    ("Giresun", "Yağlıdere"): "28610–28612",
    ("Kars", "Arpaçay"): "36730–36732",
    ("Artvin", "Kemalpaşa"): "",
    ("Denizli", "Baklan"): "",
    ("İzmir", "Menderes"): "",
}

# The article disambiguates two districts by name; use the official names.
DISTRICT_NAMES = {
    ("Zonguldak", "Karadeniz Ereğli"): "Ereğli",
}


def fetch(source: str | None) -> str:
    if source:
        raw = Path(source).read_text(encoding="utf-8")
    else:
        req = urllib.request.Request(
            API.format(rev=REVISION), headers={"User-Agent": "adres-build-data/1.0"}
        )
        with urllib.request.urlopen(req, timeout=30) as resp:
            raw = resp.read().decode("utf-8")
    return json.loads(raw)["parse"]["wikitext"]


def _cell(text: str) -> str:
    text = re.sub(r'^\s*style="[^"]*"\s*\|', "", text)
    text = re.sub(r'^\s*rowspan="\d+"\s*\|', "", text)
    text = re.sub(r"<ref[^>]*/>|<ref.*?</ref>", "", text)
    text = re.sub(r"\{\{[^}]*\}\}", "", text).replace("'''", "")
    link = re.search(r"\[\[(?:[^|\]]*\|)?([^\]]*)\]\]", text)
    return (link.group(1) if link else text).strip()


def parse_table(wikitext: str) -> list[tuple[str, str, str]]:
    table = wikitext[wikitext.index("{|") :]
    table = table[: table.index("\n|}")]
    rows = []
    for block in table.split("\n|-")[1:]:
        cells = [_cell(line[1:]) for line in block.strip().split("\n") if line.startswith("|")]
        if len(cells) >= 9:
            rows.append((cells[0], cells[1], cells[8]))
    return rows


def ranges(text: str) -> list[tuple[int, int]]:
    out = []
    for part in text.split(","):
        codes = re.findall(r"\d{5}", part)
        if codes:
            out.append((int(codes[0]), int(codes[-1])))
    return out


def build(rows: list[tuple[str, str, str]]) -> str:
    provinces = sorted({il for il, _, _ in rows})
    if len(provinces) != 81 or len(rows) != 973:
        raise SystemExit(f"expected 81 provinces / 973 districts, got {len(provinces)}/{len(rows)}")

    fixed = [
        (il, DISTRICT_NAMES.get((il, ilce), ilce), POSTAL_FIXES.get((il, ilce), posta))
        for il, ilce, posta in rows
    ]

    # The first two digits of a postal code are the province's plate number.
    prefixes: dict[str, Counter[int]] = {il: Counter() for il in provinces}
    for il, _, posta in fixed:
        for lo, hi in ranges(posta):
            prefixes[il].update([lo // 1000, hi // 1000])
    plate = {il: prefixes[il].most_common(1)[0][0] for il in provinces}
    if sorted(plate.values()) != list(range(1, 82)):
        raise SystemExit("plate numbers derived from postal codes are not 1..81")
    for il, ilce, posta in fixed:
        for lo, hi in ranges(posta):
            if lo // 1000 != plate[il] or hi // 1000 != plate[il]:
                raise SystemExit(f"postal range {posta} does not belong to {il} ({ilce})")

    lines = [
        '"""Provinces, districts and postal ranges of Turkey.',
        "",
        "Generated by scripts/build_data.py from Turkish Wikipedia, article",
        f'"Türkiye\'nin ilçeleri", revision {REVISION} (CC BY-SA). Do not edit by hand.',
        '"""',
        "",
        "# plate number -> province",
        "PROVINCES: dict[int, str] = {",
    ]
    for il in sorted(provinces, key=plate.__getitem__):
        lines.append(f"    {plate[il]}: {json.dumps(il, ensure_ascii=False)},")
    lines += [
        "}",
        "",
        "# (plate number, district, ((first postal code, last postal code), ...))",
        "DISTRICTS: tuple[tuple[int, str, tuple[tuple[int, int], ...]], ...] = (",
    ]
    for il, ilce, posta in sorted(fixed, key=lambda r: (plate[r[0]], r[1])):
        rng = "".join(f"({lo}, {hi}), " for lo, hi in ranges(posta)).rstrip(", ")
        rng = f"({rng},)" if rng else "()"
        lines.append(f"    ({plate[il]}, {json.dumps(ilce, ensure_ascii=False)}, {rng}),")
    lines += [")", ""]
    return "\n".join(lines)


def main() -> None:
    rows = parse_table(fetch(sys.argv[1] if len(sys.argv) > 1 else None))
    OUT.write_text(build(rows), encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(rows)} districts)")


if __name__ == "__main__":
    main()
